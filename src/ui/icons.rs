    /// Paints the icon, tinted, centred in `rect`.
    pub fn paint(self, ui: &Ui, rect: Rect, size: f32, color: Color32) {
        let r = Rect::from_center_size(rect.center(), egui::vec2(size, size));
        egui::Image::new(self.source())
            .fit_to_exact_size(r.size())
            .tint(color)
            .paint_at(ui, r);
    }
